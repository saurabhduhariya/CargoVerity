function drawWatermark(page: PDFPage, fontBold: PDFFont) {
  const { width, height } = page.getSize();

  // Top security banner
  page.drawRectangle({
    x: 0,
    y: height - 28,
    width,
    height: 28,
    color: rgb(0.95, 0.9, 0.9),
  });

  page.drawText("*** SYNTHETIC DEMO DOCUMENT — NOT FOR CUSTOMS FILING ***", {
    x: 40,
    y: height - 19,
    size: 11,
    font: fontBold,
    color: rgb(0.8, 0.15, 0.15),
  });

  // Large diagonal watermark across center
  page.drawText("SYNTHETIC DEMO DOCUMENT — NOT FOR CUSTOMS FILING", {
    x: 35,
    y: height / 2 - 30,
    size: 16,
    font: fontBold,
    color: rgb(0.85, 0.25, 0.25),
    rotate: degrees(35),
    opacity: 0.22,
  });

  // Bottom footer notice
  page.drawText(
    "DEMO ARTIFACT ONLY: Generated by CargoVerity test fixtures. Never file with customs authorities.",
    {
      x: 50,
      y: 18,
      size: 8,
      font: fontBold,
      color: rgb(0.6, 0.2, 0.2),
    },
  );
}

export async function createSamplePdf(config: SampleDocConfig): Promise<Uint8Array> {
  const pdfDoc = await PDFDocument.create();
  // Set fixed timestamps to ensure reproducible, deterministic byte generation
  pdfDoc.setCreationDate(new Date("2026-11-04T00:00:00Z"));
  pdfDoc.setModificationDate(new Date("2026-11-04T00:00:00Z"));
  const page = pdfDoc.addPage([595.28, 841.89]); // A4
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const fontBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  const title =
    config.docType === "INVOICE"
      ? "COMMERCIAL INVOICE"
      : config.docType === "PACKING_LIST"
        ? "PACKING LIST"
        : "BILL OF LADING";

  drawWatermark(page, fontBold);

  // Document Title
  page.drawText(title, {
    x: 50,
    y: 775,
    size: 18,
    font: fontBold,
    color: rgb(0.1, 0.15, 0.3),
  });

  page.drawText(`Shipment Ref: ${config.reference}`, {
    x: 400,
    y: 780,
    size: 11,
    font: fontBold,
    color: rgb(0.2, 0.2, 0.2),
  });

  page.drawText(`Doc No: ${config.documentNumber}`, {
    x: 400,
    y: 765,
    size: 10,
    font,
    color: rgb(0.3, 0.3, 0.3),
  });

  page.drawText(`Date: ${config.issueDate}`, {
    x: 400,
    y: 750,
    size: 10,
    font,
    color: rgb(0.3, 0.3, 0.3),
  });

  // Parties Box
  page.drawRectangle({
    x: 50,
    y: 655,
    width: 240,
    height: 80,
    borderColor: rgb(0.7, 0.7, 0.7),
    borderWidth: 1,
    color: rgb(0.98, 0.98, 0.99),
  });

  page.drawText(config.docType === "BILL_OF_LADING" ? "SHIPPER / EXPORTER:" : "EXPORTER / SUPPLIER:", {
    x: 58,
    y: 720,
    size: 9,
    font: fontBold,
    color: rgb(0.2, 0.2, 0.2),
  });

  page.drawText(config.exporter, {
    x: 58,
    y: 700,
    size: 10,
    font,
    color: rgb(0.1, 0.1, 0.1),
  });

  page.drawRectangle({
    x: 305,
    y: 655,
    width: 240,
    height: 80,
    borderColor: rgb(0.7, 0.7, 0.7),
    borderWidth: 1,
    color: rgb(0.98, 0.98, 0.99),
  });

  page.drawText(config.docType === "BILL_OF_LADING" ? "CONSIGNEE / BUYER:" : "IMPORTER / BUYER:", {
    x: 313,
    y: 720,
    size: 9,
    font: fontBold,
    color: rgb(0.2, 0.2, 0.2),
  });

  page.drawText(config.importer, {
    x: 313,
    y: 700,
    size: 10,
    font,
    color: rgb(0.1, 0.1, 0.1),
  });

  // Shipping & Transport Metadata Box
  page.drawRectangle({
    x: 50,
    y: 595,
    width: 495,
    height: 50,
    borderColor: rgb(0.7, 0.7, 0.7),
    borderWidth: 1,
    color: rgb(0.96, 0.96, 0.97),
  });

  const pol = config.portOfLoading ?? "Shanghai, China";
  const pod = config.portOfDischarge ?? "Nhava Sheva, India";
  const vessel = config.vessel ?? "EVER GIVEN V.042W";
  const container = config.containerNumber ?? "MSKU-982144-0";

  page.drawText(`Port of Loading: ${pol}`, { x: 58, y: 628, size: 9, font, color: rgb(0.2, 0.2, 0.2) });
  page.drawText(`Port of Discharge: ${pod}`, { x: 58, y: 608, size: 9, font, color: rgb(0.2, 0.2, 0.2) });
  page.drawText(`Vessel: ${vessel}`, { x: 313, y: 628, size: 9, font, color: rgb(0.2, 0.2, 0.2) });
  page.drawText(`Container: ${container}`, { x: 313, y: 608, size: 9, font, color: rgb(0.2, 0.2, 0.2) });

  // Line items table
  const tableY = 570;
  page.drawRectangle({
    x: 50,
    y: tableY - 20,
    width: 495,
    height: 20,
    color: rgb(0.2, 0.3, 0.5),
  });

  page.drawText("#", { x: 58, y: tableY - 14, size: 9, font: fontBold, color: rgb(1, 1, 1) });
  page.drawText("Description", { x: 80, y: tableY - 14, size: 9, font: fontBold, color: rgb(1, 1, 1) });
  page.drawText("HSN", { x: 260, y: tableY - 14, size: 9, font: fontBold, color: rgb(1, 1, 1) });
  page.drawText("Quantity", { x: 330, y: tableY - 14, size: 9, font: fontBold, color: rgb(1, 1, 1) });
  page.drawText("Unit Price", { x: 410, y: tableY - 14, size: 9, font: fontBold, color: rgb(1, 1, 1) });
  page.drawText("Line Total", { x: 480, y: tableY - 14, size: 9, font: fontBold, color: rgb(1, 1, 1) });

  let currentY = tableY - 38;
  for (const item of config.lineItems) {
    page.drawText(String(item.lineNumber), { x: 58, y: currentY, size: 9, font, color: rgb(0.1, 0.1, 0.1) });
    page.drawText(item.description, { x: 80, y: currentY, size: 9, font, color: rgb(0.1, 0.1, 0.1) });
    page.drawText(item.hsnCode ?? "—", { x: 260, y: currentY, size: 9, font, color: rgb(0.1, 0.1, 0.1) });
    page.drawText(`${item.quantity.toLocaleString()} ${item.quantityUnit ?? "units"}`, {
      x: 330,
      y: currentY,
      size: 9,
      font,
      color: rgb(0.1, 0.1, 0.1),
    });

    if (config.docType === "INVOICE" && item.unitPrice !== undefined) {
      const cur = item.currency ?? config.currency ?? "USD";
      page.drawText(`${cur} ${item.unitPrice.toFixed(2)}`, {
        x: 410,
        y: currentY,
        size: 9,
        font,
        color: rgb(0.1, 0.1, 0.1),
      });
      const total = item.lineTotal ?? item.quantity * item.unitPrice;
      page.drawText(`${cur} ${total.toLocaleString(undefined, { minimumFractionDigits: 2 })}`, {
        x: 480,
        y: currentY,
        size: 9,
        font,
        color: rgb(0.1, 0.1, 0.1),
      });
    } else {
      page.drawText("—", { x: 410, y: currentY, size: 9, font, color: rgb(0.4, 0.4, 0.4) });
      page.drawText("—", { x: 480, y: currentY, size: 9, font, color: rgb(0.4, 0.4, 0.4) });
    }

    currentY -= 22;
  }

  // Summary box
  const summaryY = Math.min(currentY - 15, 450);
  page.drawRectangle({
    x: 50,
    y: summaryY - 80,
    width: 495,
    height: 80,
    borderColor: rgb(0.7, 0.7, 0.7),
    borderWidth: 1,
    color: rgb(0.98, 0.98, 0.99),
  });

  page.drawText("SHIPMENT TOTALS & SPECIFICATIONS", {
    x: 58,
    y: summaryY - 15,
    size: 9,
    font: fontBold,
    color: rgb(0.2, 0.2, 0.2),
  });

  page.drawText(`Gross Weight: ${config.grossWeightKg.toLocaleString()} kg`, {
    x: 58,
    y: summaryY - 35,
    size: 10,
    font: fontBold,
    color: rgb(0.1, 0.1, 0.1),
  });

  if (config.netWeightKg) {
    page.drawText(`Net Weight: ${config.netWeightKg.toLocaleString()} kg`, {
      x: 58,
      y: summaryY - 55,
      size: 9,
      font,
      color: rgb(0.3, 0.3, 0.3),
    });
  }

  const pkgText = config.packageCount ? `${config.packageCount} ${config.packageType ?? "packages"}` : "—";
  page.drawText(`Total Packages: ${pkgText}`, {
    x: 230,
    y: summaryY - 35,
    size: 10,
    font,
    color: rgb(0.2, 0.2, 0.2),
  });

  if (config.docType === "INVOICE" && config.invoiceTotal !== undefined) {
    const cur = config.currency ?? "USD";
    page.drawText(`Total Invoice Amount: ${cur} ${config.invoiceTotal.toLocaleString(undefined, { minimumFractionDigits: 2 })}`, {
      x: 230,
      y: summaryY - 55,
      size: 11,
      font: fontBold,
      color: rgb(0.1, 0.2, 0.6),
    });
  }

  // Optional notes / scenario remarks
  if (config.notes) {
    page.drawText(`Remarks: ${config.notes}`, {
      x: 58,
      y: summaryY - 72,
      size: 8,
      font,
      color: rgb(0.4, 0.4, 0.4),
    });
  }

  // Scenario specific effects
  if (config.scenario === "low_confidence") {
    // Add overlapping, faint text to simulate OCR ambiguity
    page.drawText("OVERPRINT / RETRY SCAN [CONFIDENCE < 0.85 TEST]", {
      x: 75,
      y: summaryY - 50,
      size: 12,
      font: fontBold,
      color: rgb(0.6, 0.6, 0.6),
      opacity: 0.45,
    });
  }

  if (config.scenario === "unreadable") {
    // Draw heavy hatching across the data area to simulate severe degradation/unreadable page
    for (let offset = 0; offset < 495; offset += 15) {
      page.drawLine({
        start: { x: 50 + offset, y: tableY },
        end: { x: 50 + offset + 20, y: summaryY - 80 },
        thickness: 1.5,
        color: rgb(0.5, 0.5, 0.5),
        opacity: 0.35,
      });
    }
    page.drawText("UNREADABLE PAGE SIMULATION — MANUAL ENTRY REQUIRED", {
      x: 80,
      y: 500,
      size: 12,
      font: fontBold,
      color: rgb(0.7, 0.1, 0.1),
      opacity: 0.6,
    });
  }

  return pdfDoc.save();
}

