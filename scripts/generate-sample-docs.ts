export async function generateAllSampleDocs(targetDir: string = outputDir): Promise<string[]> {
  await mkdir(targetDir, { recursive: true });
  const generatedPaths: string[] = [];

  for (const item of sampleFixtures) {
    const pdfBytes = await createSamplePdf(item.config);
    const filePath = join(targetDir, item.fileName);
    await writeFile(filePath, pdfBytes);
    generatedPaths.push(filePath);
  }

  return generatedPaths;
}

